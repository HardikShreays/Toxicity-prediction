"""B6 - LaTeX tables for the Phase 2 GNN report sections, built from the saved C4 / summary files.

Nothing here computes a metric: it only aggregates the scorer's output (tox.metrics -> C4 files)
with the same recipe as tox.aggregate (12-task mean per run, then mean/std over the 3 runs), in
memory. It never writes results/summary.csv, headline.csv or the README (Hardik's shared files).

    python -m tox.gnn_report          # -> report/phase2/gnn_results_tables.tex
"""
from __future__ import annotations

import pandas as pd

from tox.aggregate import load_all
from tox.constants import ABLATIONS, ROOT

OUT = ROOT / "report" / "phase2" / "gnn_results_tables.tex"
FAMILIES = ["scaffold_det", "scaffold", "random"]
GNN = ["gcn", "mpnn", "afp"]
AML = ["lr_fp", "lr_fpdesc", "rf_fp", "rf_fpdesc", "xgb_fp", "xgb_fpdesc"]


def headline_frame(df: pd.DataFrame) -> pd.DataFrame:
    """model x split-family: 12-task mean per run, then mean/std over runs (aggregate.py recipe)."""
    per_run = df.groupby(["model", "split", "seed"], sort=False)[["roc_auc", "pr_auc", "pos_rate"]].mean()
    return (per_run.groupby(["model", "split"], sort=False)
                   .agg(n_runs=("roc_auc", "size"),
                        roc_auc_mean=("roc_auc", "mean"), roc_auc_std=("roc_auc", "std"),
                        pr_auc_mean=("pr_auc", "mean"), pr_auc_std=("pr_auc", "std"),
                        pos_rate=("pos_rate", "mean"))
                   .reset_index())


def _cell(g: pd.DataFrame, split: str, key: str) -> str:
    if split not in g.index:
        return "--"
    r = g.loc[split]
    std = "--" if pd.isna(r[key + "_std"]) else f"{r[key + '_std']:.3f}"
    return f"{r[key + '_mean']:.3f} $\\pm$ {std}"


def main_table(headline: pd.DataFrame, models=None) -> str:
    """Test ROC-AUC / PR-AUC (mean $\\pm$ std over 3 runs) per model and split family, GNNs first.
    No row is marked 'best': choosing it by test score would be selection on the test set."""
    models = [m for m in (models or GNN + AML) if m in set(headline.model)]
    rows = []
    for m in models:
        g = headline[headline.model == m].set_index("split")
        rows.append(f"{m.replace('_', chr(92) + '_')} & " + " & ".join(_cell(g, s, "roc_auc") for s in FAMILIES)
                    + " & " + " & ".join(_cell(g, s, "pr_auc") for s in FAMILIES) + r" \\")
    base = headline.groupby("split").pos_rate.mean()
    base_row = ("positive rate (random PR-AUC) & \\multicolumn{3}{c}{} & "
                + " & ".join(f"{base[s]:.3f}" if s in base else "--" for s in FAMILIES) + r" \\")
    return "\n".join([
        r"\begin{table*}[t]", r"\centering",
        r"\caption{Test ROC-AUC and PR-AUC, 12-endpoint mean, mean $\pm$ std over 3 runs "
        r"(\texttt{scaffold\_det}: seeds 0--2; \texttt{scaffold}, \texttt{random}: the three seeded splits). "
        r"PR-AUC is only comparable within a column; the bottom row is the random-classifier level.}",
        r"\label{tab:gnn-main}", r"\small", r"\begin{tabular}{lcccccc}", r"\toprule",
        r" & \multicolumn{3}{c}{ROC-AUC} & \multicolumn{3}{c}{PR-AUC} \\",
        r"model & scaffold\_det & scaffold & random & scaffold\_det & scaffold & random \\", r"\midrule",
        *rows, r"\midrule", base_row, r"\bottomrule", r"\end{tabular}", r"\end{table*}"])


def ablation_table(summary: pd.DataFrame) -> str:
    """One row per ablation arm from results/ablations/gnn/summary.csv (baseline = main mpnn)."""
    rows = []
    for _, r in summary.iterrows():
        std = lambda v: "--" if pd.isna(v) else f"{v:.3f}"
        rows.append(f"{r.group} & {r.variant.replace('_', chr(92) + '_')} & {int(r.n_runs)} & "
                    f"{r.roc_auc_mean:.3f} $\\pm$ {std(r.roc_auc_std)} & {r.pr_auc_mean:.3f} $\\pm$ {std(r.pr_auc_std)} \\\\")
    return "\n".join([
        r"\begin{table}[t]", r"\centering",
        r"\caption{MPNN ablations on \texttt{scaffold\_det}: test ROC-AUC and PR-AUC (12-endpoint mean, "
        r"mean $\pm$ std over seeds). One factor changes per arm; the baseline is the main \texttt{mpnn}.}",
        r"\label{tab:gnn-ablation}", r"\small", r"\begin{tabular}{llccc}", r"\toprule",
        r"group & arm & runs & ROC-AUC & PR-AUC \\", r"\midrule", *rows, r"\bottomrule", r"\end{tabular}", r"\end{table}"])


def main():
    parts = ["% GENERATED by python -m tox.gnn_report from results/metrics and results/ablations/gnn/summary.csv",
             main_table(headline_frame(load_all()))]
    summ = ABLATIONS / "gnn" / "summary.csv"
    if summ.exists():
        parts.append(ablation_table(pd.read_csv(summ)))
    OUT.write_text("\n\n".join(parts) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
